"""Build FinExpert chat-format datasets from FinQA and TAT-QA.

Usage (from the repo root, after cloning the sources):

    git clone https://github.com/czyssrs/FinQA.git data/external/raw/FinQA
    git clone https://github.com/NExTplusplus/TAT-QA.git data/external/raw/TAT-QA
    uv run python scripts/build_external_dataset.py

Outputs, per source, in data/external/<source>/:
    train.jsonl            training-eligible examples only
    train_excluded.jsonl   excluded training examples, with the reason
    validation.jsonl       all official dev examples (flags kept)
    test.jsonl             all official test examples (flags kept) - final evaluation only
and data/external/audit.json + data/external/SAMPLES.md (both committed).
"""

from __future__ import annotations

import argparse
import json
import random
import subprocess
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from finexpert.data.external import finqa, tatqa  # noqa: E402
from finexpert.data.external.common import MAX_TRAIN_TOKENS, sha256_file, write_jsonl  # noqa: E402

SPLITS = ("train", "validation", "test")


def exclusion_reasons(record: dict) -> list[str]:
    flags = record["flags"]
    reasons = []
    if flags.get("executor_matches_gold") is False:
        reasons.append("executor_mismatch")
    if flags.get("written_answer_consistent") is False:
        reasons.append("written_answer_inconsistent")
    if flags.get("derivation_consistent") is False:
        reasons.append("derivation_inconsistent")
    if flags["est_tokens"] > MAX_TRAIN_TOKENS:
        reasons.append("too_long")
    return reasons


def git_commit(path: Path) -> str | None:
    try:
        return subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def samples_markdown(by_source: dict[str, list[dict]], seed: int = 7) -> str:
    rng = random.Random(seed)
    lines = ["# Converted examples (random training samples)", "",
             "Generated by `scripts/build_external_dataset.py`. Context shortened here for reading; "
             "the training files contain the full excerpt.", ""]
    for source, records in by_source.items():
        by_type: dict[str, list[dict]] = {}
        for record in records:
            by_type.setdefault(record["answer_type"], []).append(record)
        for answer_type, items in sorted(by_type.items()):
            record = rng.choice(items)
            user = record["messages"][1]["content"]
            question = user.split("\nQuestion: ", 1)[1].split("\n\n", 1)[0]
            context = user.split("\nQuestion: ", 1)[0]
            short = context if len(context) <= 900 else context[:900] + " …"
            lines += [f"## {source} · {answer_type} · {record['difficulty']} · `{record['example_id']}`", "",
                      "**Context**", "", "```text", short, "```", "",
                      f"**Question:** {question}", "", "**Target**", "", "```text",
                      record["messages"][2]["content"], "```", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--finqa-dir", type=Path, default=Path("data/external/raw/FinQA"))
    parser.add_argument("--tatqa-dir", type=Path, default=Path("data/external/raw/TAT-QA"))
    parser.add_argument("--out", type=Path, default=Path("data/external"))
    args = parser.parse_args()

    sources = {"finqa": (finqa, args.finqa_dir), "tatqa": (tatqa, args.tatqa_dir)}
    audit: dict = {"max_train_tokens_estimate": MAX_TRAIN_TOKENS, "sources": {}}
    train_by_source: dict[str, list[dict]] = {}

    for name, (module, directory) in sources.items():
        if not directory.exists():
            sys.exit(f"Missing {directory}. Clone the source repository first (see this script's docstring).")
        source_audit: dict = {"source_dir": str(directory), "source_commit": git_commit(directory), "splits": {}}
        for split in SPLITS:
            records = module.convert_split(directory, split)
            split_audit: dict = {
                "total": len(records),
                "answer_types": dict(Counter(r["answer_type"] for r in records)),
                "difficulty": dict(Counter(r["difficulty"] for r in records)),
                "would_be_excluded": dict(Counter(reason for r in records for reason in exclusion_reasons(r))),
            }
            if split == "train":
                kept, excluded = [], []
                for record in records:
                    reasons = exclusion_reasons(record)
                    if reasons:
                        excluded.append({**record, "excluded_because": reasons})
                    else:
                        kept.append(record)
                write_jsonl(args.out / name / "train.jsonl", kept)
                write_jsonl(args.out / name / "train_excluded.jsonl", excluded)
                split_audit.update({"kept": len(kept), "excluded": len(excluded),
                                    "kept_answer_types": dict(Counter(r["answer_type"] for r in kept))})
                train_by_source[name] = kept
            else:
                write_jsonl(args.out / name / f"{split}.jsonl", records)
            source_audit["splits"][split] = split_audit
        source_audit["sha256"] = {path.name: sha256_file(path) for path in sorted((args.out / name).glob("*.jsonl"))}
        audit["sources"][name] = source_audit

    (args.out / "audit.json").write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    (args.out / "SAMPLES.md").write_text(samples_markdown(train_by_source), encoding="utf-8")

    for name, source_audit in audit["sources"].items():
        train = source_audit["splits"]["train"]
        print(f"{name:6s} train kept {train['kept']:>6} / {train['total']:<6} excluded {train['excluded']:>5} "
              f"{train['would_be_excluded']}  | validation {source_audit['splits']['validation']['total']}"
              f"  test {source_audit['splits']['test']['total']}")
    print(f"Wrote {args.out}/audit.json and {args.out}/SAMPLES.md")


if __name__ == "__main__":
    main()
